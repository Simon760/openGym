function callTool(name, args, S) {
  switch (name) {
    case 'get_training_log': {
      const days = args.days === 0 ? 0 : (num(args.days) || 30);
      const now = Date.now();
      return {
        from: days ? iso(now - days * 86400000) : null,
        to: today(),
        unit: S.unit || 'kg',
        weight_goal: S.targetW || null,
        intake_goal: S.nutriGoal || null,
        tdee: tdeeOut(S.tdee),
        watch_trim: watchTrim(S),
        activity: (S.health || []).filter(e => inWindow(e.d, days, now))
          .map(e => compact({
            date: e.d,
            kcal: e.kcal ? Math.round(e.kcal * (1 - watchTrim(S))) : null,
            kcal_raw: e.kcal || null,
            steps: e.steps, resting_hr: e.rhr
          })),
        sleep: (S.sleep || []).filter(e => inWindow(e.d, days, now))
          .map(e => compact({ date: e.d, bed: e.bed, wake: e.wake, awake_min: e.awake, hours: e.h, felt: e.q })),
        body_weight: (S.bodyweight || []).filter(b => inWindow(b.d, days, now)).map(b => ({ date: b.d, kg: b.w })),
        intake: (S.nutrition || []).filter(e => inWindow(e.d, days, now))
          .map(e => ({ date: e.d, kcal: e.kcal, protein: e.p, carbs: e.c, fat: e.f })),
        workouts: (S.workouts || []).filter(w => inWindow(w.d, days, now)).map(w => sessionOut(w, S.customEx))
      };
    }
    case 'get_plan':
      return planOut(S);

    case 'log_intake': {
      const d = /^\d{4}-\d{2}-\d{2}$/.test(args.date || '') ? args.date : today();
      const entry = { d, t: Date.now() };
      const map = { kcal: 'kcal', protein: 'p', carbs: 'c', fat: 'f' };
      for (const [from, to] of Object.entries(map)) { const v = num(args[from]); if (v) entry[to] = v; }
      const rest = (S.nutrition || []).filter(e => e.d !== d);
      // Every field blank clears the day, matching the app: that is how a mistake is undone.
      S.nutrition = (Object.keys(entry).length > 2 ? [...rest, entry] : rest).sort((a, b) => (a.d < b.d ? -1 : 1));
      return { ok: true, date: d, logged: Object.keys(entry).length > 2 };
    }
    case 'log_weight': {
      const kg = num(args.kg);
      if (!kg) throw new Error('kg must be a positive number');
      const d = /^\d{4}-\d{2}-\d{2}$/.test(args.date || '') ? args.date : today();
      const rest = (S.bodyweight || []).filter(b => b.d !== d);
      S.bodyweight = [...rest, { d, w: kg, t: Date.now() }].sort((a, b) => (a.d < b.d ? -1 : 1));
      return { ok: true, date: d, kg };
    }
    case 'log_history': {
      if (!Array.isArray(args.days) || !args.days.length) throw new Error('days must be a non-empty array');
      if (args.days.length > 2000) throw new Error('at most 2000 days per call');
      const put = (list, entry, keys) => {
        const rest = (list || []).filter(e => e.d !== entry.d);
        const kept = { d: entry.d, t: Date.now() };
        for (const k of keys) if (entry[k] != null) kept[k] = entry[k];
        // A day carrying nothing but its date is dropped, not stored as a row of blanks.
        return (Object.keys(kept).length > 2 ? [...rest, kept] : rest).sort(byDay);
      };
      let written = 0, skipped = 0;
      for (const d of args.days) {
        if (!/^\d{4}-\d{2}-\d{2}$/.test(d && d.date || '')) { skipped++; continue; }
        const day = d.date;
        let touched = false;

        const kg = num(d.kg), bf = num(d.body_fat);
        if (kg) {
          const ex = (S.bodyweight || []).find(b => b.d === day);
          S.bodyweight = put(S.bodyweight, { d: day, w: kg, bf: bf || (ex && ex.bf) || null }, ['w', 'bf']);
          touched = true;
        }
        const eaten = { d: day, kcal: num(d.kcal), p: num(d.protein), c: num(d.carbs), f: num(d.fat) };
        if (eaten.kcal || eaten.p || eaten.c || eaten.f) {
          const ex = (S.nutrition || []).find(e => e.d === day) || {};
          for (const k of ['kcal', 'p', 'c', 'f']) if (eaten[k] == null) eaten[k] = ex[k] != null ? ex[k] : null;
          S.nutrition = put(S.nutrition, eaten, ['kcal', 'p', 'c', 'f']);
          touched = true;
        }
        const sport = num(d.sport_kcal), steps = num(d.steps);
        if (sport || steps) {
          const ex = (S.health || []).find(e => e.d === day) || {};
          S.health = put(S.health, {
            d: day, kcal: sport || ex.kcal || null, steps: steps ? Math.round(steps) : ex.steps || null
          }, ['kcal', 'steps']);
          touched = true;
        }
        const slept = num(d.sleep_hours);
        if (slept && slept >= 0.5 && slept <= 16) { S.sleep = put(S.sleep, { d: day, h: slept }, ['h']); touched = true; }

        if (touched) written++; else skipped++;
      }
      return { ok: true, written, skipped };
    }
    case 'propose_program': {
      if (!args.program || typeof args.program !== 'object') throw new Error('program must be an object');
      if (!Array.isArray(args.program.routines) || !args.program.routines.length) {
        throw new Error('program.routines must be a non-empty array');
      }
      // Parked, not applied. Resolving names needs the exercise library and the matcher,
      // both of which live in the app — and a program rewriting someone's training deserves
      // a look before it lands, which is exactly what the app's review screen is.
      S.pendingProgram = { at: Date.now(), program: args.program };
      return {
        ok: true,
        status: 'waiting for the user to review it in openGym',
        routines: args.program.routines.length
      };
    }
    default:
      throw new Error(`unknown tool: ${name}`);
  }
}

const WRITES = new Set(['log_intake', 'log_weight', 'log_history', 'propose_program']);

/* ------------------------------------------------------------------ handler -- */

const rpc = (id, result) => ({ jsonrpc: '2.0', id, result });
const rpcError = (id, code, message) => ({ jsonrpc: '2.0', id, error: { code, message } });

/**
 * ctx: { readState(uid), writeState(uid, S), uid, readBody(req), json(res, code, obj) }
 */
export async function handleMcp(req, res, token, ctx) {
  if (!mcpEnabled() || !tokenOk(token)) return ctx.json(res, 404, { error: 'not found' });
  if (!ctx.uid) return ctx.json(res, 503, { error: 'no profile to serve — set MCP_UID' });

  let msg;
  try { msg = await ctx.readBody(req); } catch { return ctx.json(res, 400, rpcError(null, -32700, 'parse error')); }
  const id = msg && msg.id !== undefined ? msg.id : null;
  const method = msg && msg.method;

  // Notifications carry no id and expect no body — answering one with a result is a
  // protocol error, not a harmless extra.
  if (method && method.startsWith('notifications/')) { res.writeHead(202).end(); return; }

  if (method === 'initialize') {
    const asked = msg.params && msg.params.protocolVersion;
    return ctx.json(res, 200, rpc(id, {
      protocolVersion: /^\d{4}-\d{2}-\d{2}$/.test(asked || '') ? asked : FALLBACK_PROTOCOL,
      capabilities: { tools: { listChanged: false } },
      serverInfo: { name: 'openGym', version: '1.2.4' }
    }));
  }
  if (method === 'ping') return ctx.json(res, 200, rpc(id, {}));
  if (method === 'tools/list') return ctx.json(res, 200, rpc(id, { tools: TOOLS }));

  if (method === 'tools/call') {
    const name = msg.params && msg.params.name;
    const args = (msg.params && msg.params.arguments) || {};
    const S = ctx.readState(ctx.uid);
    if (!S) return ctx.json(res, 200, rpc(id, { isError: true, content: [{ type: 'text', text: 'no data for this profile yet' }] }));
    try {
      const out = callTool(name, args, S);
      if (WRITES.has(name)) {
        // The app takes the server's copy only when its timestamp is at least as new as the
        // local one, so a write that does not move _ts forward is a write the app ignores.
        S._ts = Date.now();
        ctx.writeState(ctx.uid, S);
      }
      return ctx.json(res, 200, rpc(id, { content: [{ type: 'text', text: JSON.stringify(out, null, 1) }] }));
    } catch (e) {
      // A tool that failed reports through the result, not as a transport error: the caller
      // is a model that can read the reason and try again.
      return ctx.json(res, 200, rpc(id, { isError: true, content: [{ type: 'text', text: String(e.message || e) }] }));
    }
  }

  return ctx.json(res, 200, rpcError(id, -32601, `method not found: ${method}`));
}
