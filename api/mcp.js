/* MCP endpoint — lets a Claude conversation read your training log and write to it.
 *
 * Off unless MCP_TOKEN is set, like the admin dashboard: a fresh instance exposes nothing.
 *
 * AUTH — the token is part of the URL: POST /api/mcp/<MCP_TOKEN>. A claude.ai custom
 * connector is configured with a URL and, optionally, OAuth credentials; it has nowhere to
 * put a custom header. So the URL itself is the credential, which makes it a secret with
 * all that implies:
 *   · anyone holding the URL has your whole log and can write to it — do not paste it
 *     anywhere you would not paste a password
 *   · nginx logs request paths by default, so web/nginx.conf and nginx.conf stop logging
 *     this one; check any proxy in front of them does the same
 *   · rotating it means changing MCP_TOKEN and re-adding the connector
 * OAuth would avoid all three and is the right answer for anything shared. This is the
 * simplest thing that is not "no auth at all", for one person's own instance.
 *
 * TRANSPORT — JSON-RPC 2.0 over a single POST, answered as JSON. No SSE: every tool here
 * answers immediately out of a file on disk, so there is nothing to stream, and a streaming
 * transport would be more moving parts for no gain.
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = path.dirname(fileURLToPath(import.meta.url));
// id -> name, generated by scripts/build-exercise-names.mjs. Without it a session reads as
// a list of opaque ids, which is useless to whatever is doing the coaching.
let NAMES = {};
try { NAMES = JSON.parse(fs.readFileSync(path.join(HERE, 'exercise-names.json'), 'utf8')); }
catch { console.error('mcp: exercise-names.json missing — run scripts/build-exercise-names.mjs'); }

// The version the client asks for is echoed back when it looks like a version at all: a
// simple server that implements one request/response shape is compatible across the
// revisions that shape has not changed in, and pinning one would break on the next.
const FALLBACK_PROTOCOL = '2025-06-18';

const TOKEN = process.env.MCP_TOKEN || '';
export const mcpEnabled = () => TOKEN.length >= 16;

/** Constant-time compare, so a wrong token cannot be found one character at a time. */
function tokenOk(given) {
  const a = Buffer.from(String(given || ''));
  const b = Buffer.from(TOKEN);
  return a.length === b.length && crypto.timingSafeEqual(a, b);
}

/** The path this endpoint answers on, or null when it is not that path. */
export function mcpPath(pathname) {
  const m = /^\/api\/mcp\/(.+)$/.exec(pathname);
  return m ? m[1] : null;
}

/* ------------------------------------------------------------------ shaping -- */

const iso = d => new Date(d).toISOString().slice(0, 10);
const today = () => iso(Date.now());
const inWindow = (day, days, now) =>
  !days || new Date(day + 'T12:00:00').getTime() > now - days * 86400000;

const exName = (id, customEx) =>
  NAMES[id] || (customEx || []).find(c => c.id === id)?.n || id;

/** One logged set, in the terms it was logged in. */
function setOut(s) {
  const o = {};
  if (s.w) o.weight = s.w;
  if (s.r != null) o.reps = s.r;
  if (s.sec != null) o.seconds = s.sec;
  if (s.min != null) o.minutes = s.min;
  if (s.speed != null) o.speed = s.speed;
  if (s.rir != null) o.rir = s.rir;
  if (s.rpe != null) o.rpe = s.rpe;
  return o;
}

/**
 * A finished session. The prescription travels beside the sets — without it nothing on the
 * other end can say whether the session hit what it was asked for, which is the whole
 * signal a program gets adjusted on.
 */
function sessionOut(w, customEx) {
  return {
    date: w.d,
    routine: w.name,
    minutes: w.start && w.end ? Math.round((w.end - w.start) / 60000) : null,
    bodyweight: w.bw || null,
    volume: w.vol || null,
    personal_records: (w.prs || []).map(id => exName(id, customEx)),
    exercises: (w.entries || []).map(e => ({
      exercise: exName(e.id, customEx),
      target: e.target
        ? { sets: e.target.sets, reps: e.target.reps, seconds: e.target.sec, weight: e.target.weight }
        : null,
      sets: (e.sets || []).filter(s => s.done).map(setOut)
    }))
  };
}

// Absent fields are dropped rather than sent as null: the payload is read by a model, and
// a wall of "increment: null" is tokens spent saying nothing.
const compact = o => Object.fromEntries(Object.entries(o).filter(([, v]) => v != null));

function planOut(S) {
  const DAYS = ['sunday', 'monday', 'tuesday', 'wednesday', 'thursday', 'friday', 'saturday'];
  const week = {};
  DAYS.forEach((name, d) => {
    const r = (S.routines || []).find(x => x.id === (S.week || {})[d]);
    week[name] = r ? r.name : 'rest';
  });
  return {
    week,
    routines: (S.routines || []).map(r => compact({
      name: r.name,
      progression: r.prog,
      exercises: (r.ex || []).map(e => compact({
        exercise: exName(e.id, S.customEx),
        sets: e.sets, reps: e.reps, weight: e.weight,
        seconds: e.sec, minutes: e.min, speed: e.speed,
        reps_min: e.repsMin, reps_max: e.repsMax,
        progression: e.prog, increment: e.inc,
        per_side: e.side || undefined, superset: e.sg
      }))
    }))
  };
}

/* -------------------------------------------------------------------- tools -- */

const num = v => (Number.isFinite(+v) && +v > 0 ? +v : null);
const byDay = (a, b) => (a.d < b.d ? -1 : a.d > b.d ? 1 : 0);

// Maintenance as the app stores it. A profile written before the breakdown holds a bare
// number, which meant expenditure without training — a breakdown budgeting none.
const TDEE_PARTS = ['bmr', 'neat', 'other', 'sport'];
function tdeeOut(v) {
  if (v == null) return null;
  if (typeof v === 'number') return { bmr: 0, neat: 0, other: v, sport: 0, total: v };
  if (typeof v !== 'object') return null;
  const p = {};
  let total = 0;
  for (const k of TDEE_PARTS) { p[k] = Math.round(num(v[k]) || 0); total += p[k]; }
  return total > 0 ? { ...p, total } : null;
}
// An explicit 0 is a choice to trust the watch, not a missing value.
const watchTrim = S =>
  (Number.isFinite(+S.watchTrim) && +S.watchTrim >= 0 && +S.watchTrim <= 0.6 ? +S.watchTrim : 0.3);

